#!/usr/bin/env node
// Regenerates the frozen data modules in src/data/ from upstream sources.
//
// WARNING: the generated data is part of the fingerprint algorithm. Changing it
// changes every story, so a regenerated dataset MUST ship with a new algorithm
// version (see src/core/version.ts) and updated golden test vectors.
//
// Usage: node scripts/build-data.mjs   (downloads into tmp/data if missing)
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const TMP = join(ROOT, 'tmp/data');
const OUT = join(ROOT, 'src/data');
const CITY_COUNT = 2048;

const SOURCES = {
  'cities15000.zip': 'https://download.geonames.org/export/dump/cities15000.zip',
  'countryInfo.txt': 'https://download.geonames.org/export/dump/countryInfo.txt',
  'ne_50m_land.geojson':
    'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_land.geojson',
  'english.txt': 'https://raw.githubusercontent.com/bitcoin/bips/master/bip-0039/english.txt',
};

mkdirSync(TMP, { recursive: true });
mkdirSync(OUT, { recursive: true });
for (const [file, url] of Object.entries(SOURCES)) {
  if (!existsSync(join(TMP, file))) {
    console.log(`downloading ${url}`);
    execFileSync('curl', ['-sSfL', '-o', join(TMP, file), url]);
  }
}
if (!existsSync(join(TMP, 'cities15000.txt'))) {
  execFileSync('unzip', ['-o', join(TMP, 'cities15000.zip'), '-d', TMP]);
}

const header = (what) =>
  `// GENERATED by scripts/build-data.mjs — DO NOT EDIT.\n// ${what}\n`;

// ---------------------------------------------------------------- countries
const countries = new Map();
for (const line of readFileSync(join(TMP, 'countryInfo.txt'), 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const f = line.split('\t');
  countries.set(f[0], f[4].trim());
}

// ------------------------------------------------------------------- cities
const FOLD = { Ł: 'L', ł: 'l', Ø: 'O', ø: 'o', Đ: 'D', đ: 'd', ß: 'ss', Æ: 'Ae', æ: 'ae', Œ: 'Oe', œ: 'oe', ı: 'i', Ħ: 'H', ħ: 'h', 'ʻ': "'", 'ʼ': "'", '’': "'", 'ʿ': "'", 'ʾ': "'" };
// "Łódź" -> "Lodz" (GeoNames' own ASCII names use German-style "Duesseldorf").
const foldAscii = (s) =>
  s
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[\u0080-\uffff]/g, (ch) => FOLD[ch] ?? ch);
const NAME_RE = /^[A-Za-z][A-Za-z .'-]{1,16}[a-z]$/;

const EXCLUDED_CODES = new Set(['PPLX', 'PPLH', 'PPLQ', 'PPLW', 'PPLCH']);
const raw = [];
for (const line of readFileSync(join(TMP, 'cities15000.txt'), 'utf8').split('\n')) {
  if (!line) continue;
  const f = line.split('\t');
  const folded = foldAscii(f[1].trim());
  const name = NAME_RE.test(folded) ? folded : f[2].trim();
  if (EXCLUDED_CODES.has(f[7])) continue;
  if (!NAME_RE.test(name)) continue;
  if (!countries.has(f[8])) continue;
  raw.push({
    id: Number(f[0]),
    name,
    cc: f[8],
    lat: Number(f[4]),
    lon: Number(f[5]),
    pop: Number(f[14]),
    capital: f[7] === 'PPLC',
  });
}

// Spread cities across the world: a city's score decays with its rank inside its
// own country, so small countries still get their main cities.
const byCountry = new Map();
for (const c of raw) {
  if (!byCountry.has(c.cc)) byCountry.set(c.cc, []);
  byCountry.get(c.cc).push(c);
}
for (const list of byCountry.values()) {
  list.sort((a, b) => b.pop - a.pop || a.id - b.id);
  list.forEach((c, rank) => {
    c.score = (c.capital ? 1e9 : 0) + c.pop / Math.pow(rank + 1, 1.15);
  });
}
const candidates = [...raw].sort((a, b) => b.score - a.score || a.id - b.id);

const key = (n) => n.toLowerCase().replace(/[^a-z]/g, '');
function levenshtein(a, b) {
  if (Math.abs(a.length - b.length) > 2) return 3;
  let prev = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    const cur = [i];
    for (let j = 1; j <= b.length; j++) {
      cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
    }
    prev = cur;
  }
  return prev[b.length];
}
// Names that look alike defeat the purpose, so near-duplicates are skipped.
const tooSimilar = (a, b) => {
  const limit = Math.min(a.length, b.length) >= 8 ? 2 : 1;
  return levenshtein(a, b) <= limit;
};

const RAD = Math.PI / 180;
const distanceKm = (a, b) => {
  const h =
    Math.sin(((b.lat - a.lat) * RAD) / 2) ** 2 +
    Math.cos(a.lat * RAD) * Math.cos(b.lat * RAD) * Math.sin(((b.lon - a.lon) * RAD) / 2) ** 2;
  return 12742 * Math.asin(Math.sqrt(h));
};
// Districts of big cities (e.g. Mokotow in Warsaw) are not real destinations.
const MIN_SPACING_KM = 25;

const picked = [];
const pickedKeys = [];
for (const c of candidates) {
  if (picked.length === CITY_COUNT) break;
  const k = key(c.name);
  if (pickedKeys.some((p) => p === k || tooSimilar(p, k))) continue;
  if (picked.some((p) => distanceKm(p, c) < MIN_SPACING_KM)) continue;
  picked.push(c);
  pickedKeys.push(k);
}
if (picked.length !== CITY_COUNT) throw new Error(`only ${picked.length} cities`);
picked.sort((a, b) => a.name.localeCompare(b.name, 'en') || a.id - b.id);

const usedCountries = [...new Set(picked.map((c) => c.cc))].sort();
// Integer unit-sphere coordinates (scale 1e5) let the app rank distances with exact
// integer math, so every JS engine produces the same route.
const SCALE = 1e5;
const cityLines = picked.map((c) => {
  const lat = Number(c.lat.toFixed(2)) * RAD;
  const lon = Number(c.lon.toFixed(2)) * RAD;
  const xyz = [Math.cos(lat) * Math.cos(lon), Math.cos(lat) * Math.sin(lon), Math.sin(lat)].map((v) =>
    Math.round(v * SCALE),
  );
  return [c.name, c.cc, c.lat.toFixed(2), c.lon.toFixed(2), ...xyz].join('|');
});
writeFileSync(
  join(OUT, 'cities.ts'),
  header('Cities from GeoNames (https://www.geonames.org/, CC BY 4.0).') +
    '// Format per line: name|countryCode|latitude|longitude|x|y|z (unit sphere * 1e5)\n' +
    `export const CITIES_RAW = ${JSON.stringify(cityLines.join('\n'))};\n`,
);
writeFileSync(
  join(OUT, 'countries.ts'),
  header('Country names from GeoNames (https://www.geonames.org/, CC BY 4.0).') +
    'export const COUNTRIES: Readonly<Record<string, string>> = {\n' +
    usedCountries.map((cc) => `  ${cc}: ${JSON.stringify(countries.get(cc))},`).join('\n') +
    '\n};\n',
);

// -------------------------------------------------------------------- words
const words = readFileSync(join(TMP, 'english.txt'), 'utf8').trim().split('\n');
if (words.length !== 2048) throw new Error('BIP39 list must have 2048 words');
writeFileSync(
  join(OUT, 'words.ts'),
  header('BIP39 English word list (https://github.com/bitcoin/bips, MIT License).') +
    `export const WORDS_RAW = ${JSON.stringify(words.join(' '))};\n`,
);

// --------------------------------------------------------------------- land
// Equirectangular projection: x = lon + 180, y = 90 - lat (viewBox 0 0 360 180).
const TOLERANCE = 0.08;
function simplify(points, tol) {
  if (points.length < 3) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [s, e] = stack.pop();
    const [x1, y1] = points[s];
    const [x2, y2] = points[e];
    const dx = x2 - x1;
    const dy = y2 - y1;
    const len = Math.hypot(dx, dy);
    let maxD = 0;
    let idx = -1;
    for (let i = s + 1; i < e; i++) {
      const [x, y] = points[i];
      const d = len < 1e-9 ? Math.hypot(x - x1, y - y1) : Math.abs(dy * x - dx * y + x2 * y1 - y2 * x1) / len;
      if (d > maxD) {
        maxD = d;
        idx = i;
      }
    }
    if (maxD > tol && idx > 0) {
      keep[idx] = 1;
      stack.push([s, idx], [idx, e]);
    }
  }
  return points.filter((_, i) => keep[i]);
}
const fmt = (n) => String(Math.round(n * 10) / 10);
const land = JSON.parse(readFileSync(join(TMP, 'ne_50m_land.geojson'), 'utf8'));
const parts = [];
for (const feature of land.features) {
  const g = feature.geometry;
  const polygons = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const poly of polygons) {
    const ring = poly[0].map(([lon, lat]) => [lon + 180, 90 - lat]);
    const simple = simplify(ring, TOLERANCE);
    if (simple.length < 4) continue;
    let d = '';
    let last = '';
    simple.forEach(([x, y], i) => {
      const p = `${fmt(x)} ${fmt(y)}`;
      if (p === last) return;
      d += (i === 0 ? 'M' : 'L') + p;
      last = p;
    });
    parts.push(d + 'Z');
  }
}
writeFileSync(
  join(OUT, 'land.ts'),
  header('Land outlines from Natural Earth 1:50m (https://www.naturalearthdata.com/, public domain).') +
    '// Equirectangular SVG path: x = lon + 180, y = 90 - lat.\n' +
    `export const LAND_PATH = ${JSON.stringify(parts.join(''))};\n`,
);

console.log(`cities: ${picked.length}, countries: ${usedCountries.length}, land parts: ${parts.length}`);
const perCountry = [...byCountry.keys()]
  .map((cc) => [cc, picked.filter((c) => c.cc === cc).length])
  .filter(([, n]) => n > 0)
  .sort((a, b) => b[1] - a[1]);
console.log('top countries:', perCountry.slice(0, 15).map(([cc, n]) => `${cc}:${n}`).join(' '));
